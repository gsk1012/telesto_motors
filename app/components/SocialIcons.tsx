interface SocialIconLinkProps {
  href: string
  label: string
  children: ReactNode
}

export function SocialIconLink({ href, label, children }: SocialIconLinkProps) {
  // Alleen echte URL's openen in een nieuw tabblad; een placeholder (#) niet.
  const external = /^https?:\/\//.test(href)
  return (
    <a
      href={href}
      aria-label={label}
      {...(external ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
      className="flex h-9 w-9 items-center justify-center rounded-full border border-white/25 text-white/85 transition-colors duration-300 ease-out hover:border-bronze hover:bg-bronze hover:text-white"
    >
      {children}
    </a>
  )
}
